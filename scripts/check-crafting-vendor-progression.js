const fs = require("fs");
const path = require("path");
const assert = require("assert");
const root = path.resolve(__dirname, "..");
const game = fs.readFileSync(path.join(root, "public/game.js"), "utf8");
const html = fs.readFileSync(path.join(root, "public/index.html"), "utf8");
const server = fs.readFileSync(path.join(root, "server.js"), "utf8");
const net = fs.readFileSync(path.join(root, "public/client-network.js"), "utf8");

assert(html.includes('data-craft-filter="consumables"') && html.includes('data-craft-filter="weapons"') && html.includes('data-craft-filter="armor"'), "Crafting category tabs missing");
assert(html.includes('grid-template-columns: repeat(3, minmax(0, 1fr));'), "Crafting is not three per row");
assert(game.includes('craftCategoryFilter = "consumables"'), "Crafting should open/filter from consumables");
assert(game.includes('ingredients: Object.freeze({ wood: 8, stone: 2 })'), "Wood Helm recipe missing Stone");
assert(game.includes('ingredients: Object.freeze({ wood: 12, stone: 3 })'), "Wood Chest recipe missing Stone");
assert(game.includes('ingredients: Object.freeze({ wood: 10, stone: 2 })'), "Wood Greaves recipe missing Stone");
assert(game.includes('ingredients: Object.freeze({ wood: 8 })'), "Wood-only recipes were not increased");
assert(server.includes('MARNIE_WOOD_GOAL = 10') && server.includes('marniePickaxeReceived'), "Marnie 10-Wood Pickaxe progression missing");
assert(game.includes('"PICKAXE RECEIVED!"') && !game.includes('"BRING ME 5 WOOD"'), "Marnie client progression not updated");
assert(server.includes('cam: Object.freeze') && server.includes('myrtle: Object.freeze'), "Vendor catalogs missing");
assert(game.includes('{ id: "arrows", name: "Arrows ×50", vendor: "cam"'), "Cam Arrow stock missing");
assert(game.includes('{ id: "weapon_dreamcatcher", name: "Dreamcatcher", vendor: "cam", price: 60 }'), "Cam Dreamcatcher stock missing");
assert(game.includes('{ id: "weapon_sapgemWand", name: "Sapgem Wand", vendor: "myrtle", price: 20 }'), "Myrtle Sapgem stock missing");
assert(game.includes('weapon_dreamcatcher: Object.freeze({ level: 20 })'), "Dreamcatcher level requirement missing");
assert(game.includes('weapon_sapgemWand: Object.freeze({ level: 10 })'), "Sapgem level requirement missing");
assert(game.includes('weapon_lostKey: Object.freeze({ level: 15 })'), "Tournesol level requirement missing");
assert(game.includes('weapon_hugeSunflower: Object.freeze({ level: 20 })'), "Tabatha level requirement missing");
assert(game.includes('hat_ranger: Object.freeze({ level: 10 })'), "Ranger Lv10 requirement missing");
assert(game.includes('hat_jester: Object.freeze({ level: 20, luck: 10 })'), "Jester Lv20 requirement missing");
assert(html.includes('id="beachQuestShop"'), "Myrtle quest shop button missing");
assert(game.includes('openVendorShop("cam")') && game.includes('openVendorShop("myrtle")'), "Cam/Myrtle shop routing missing");
assert(net.includes('requestShopPurchase(itemId, vendor)') && net.includes('requestMarnieWoodTurnIn'), "Vendor/Marnie network requests missing");
assert(!server.includes('const SHOP_PRICE = 1;'), "Old one-coin shop price still active");
console.log("Crafting/vendor progression regression checks passed.");
