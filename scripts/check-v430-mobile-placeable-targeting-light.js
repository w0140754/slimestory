"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const input = fs.readFileSync(path.join(root, "public", "client-input.js"), "utf8");
const game = fs.readFileSync(path.join(root, "public", "game.js"), "utf8");
const html = fs.readFileSync(path.join(root, "public", "index.html"), "utf8");
const config = fs.readFileSync(path.join(root, "public", "client-config.js"), "utf8");
const server = fs.readFileSync(path.join(root, "server.js"), "utf8");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));

assert.strictEqual(pkg.version, "0.6.11.431");
assert(config.includes('const CLIENT_BUILD_VERSION = "6-11-431";'));
assert(server.includes('const BUILD_VERSION = "6-11-431";'));
assert(html.includes('?v=431'), "client cache markers must advance to v430");
assert(input.includes('mobileBuildCursorWorldX = null;\n  mobileBuildCursorWorldY = null;\n  mobileBuildCursorMapId = null;\n  document.body.classList.remove("mobile-build-cursor-mode");\n  updateMobilePrimaryActionButton();'), "selecting a placeable must not auto-seed a cursor");
assert(!input.includes('const leadDistance = (["woodFloor", "stoneFloor", "chest", "craftingTable"].includes(selectedBuildPiece)'), "legacy automatic lead cursor must be gone");
assert(input.includes('document.body.classList.add("mobile-build-cursor-mode");\n  updateMobilePrimaryActionButton();\n  updateCanvasCursor();'), "first world tap must activate cursor UI");
assert(input.includes('const cursorActive = Boolean('), "nudge visibility must depend on a real cursor");
assert(input.includes('nudgePad.setAttribute("aria-hidden", cursorActive ? "false" : "true")'), "nudge pad ARIA state must follow cursor activity");
assert(html.includes('body.mobile-build-selected-mode #mobileAutoAttackButton'), "AUTO must remain hidden while a placeable is held even before targeting");
assert(game.includes('!mobileBuildCursorWorldPoint()\n  ) return;'), "mobile ghost preview must be suppressed until first world tap");
assert(game.includes('const LOCAL_NIGHT_SIGHT_RADIUS = 18;'), "self night sight must be reduced to 18");
assert(game.includes('radius: 74,'), "placed Torch light radius must be reduced to 74");
assert((game.match(/radius: 68,/g) || []).length >= 2, "local and remote held Torch light radius must be reduced to 68");
console.log("v430 mobile placeable targeting + night-light polish checks passed");
